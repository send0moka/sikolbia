<div class="prose max-w-none">
    <h3 class="text-xl font-semibold text-neutral-900 mb-6">Metodologi Data Iklim, OPT, dan DPI</h3>

    <div class="grid md:grid-cols-2 gap-8">
        <div>
            <h4 class="text-lg font-medium text-neutral-900 mb-2">Sumber Data</h4>
            <ul class="space-y-1 text-neutral-700">
                <li>• Kementerian Pertanian Republik Indonesia</li>
                <li>• Direktorat Jenderal Tanaman Pangan / Hortikultura / Perkebunan</li>
                <li>• Ditjen Prasarana dan Sarana Pertanian</li>
                <li>• Badan Pusat Statistik (BPS)</li>
                <li>• BMKG (Badan Meteorologi, Klimatologi, dan Geofisika)</li>
                <li>• Dinas Pertanian Provinsi/Kabupaten</li>
            </ul>
        </div>
        <div>
            <h4 class="text-lg font-medium text-neutral-900 mb-2">Definisi Utama</h4>
            <div class="space-y-2 text-neutral-700">
                <div><strong>Iklim:</strong> Kondisi rata-rata cuaca (curah hujan, suhu, kelembapan) dalam jangka waktu tertentu.</div>
                <div><strong>OPT (Organisme Pengganggu Tanaman):</strong> Hama/penyakit yang mempengaruhi produksi/pertumbuhan tanaman.</div>
                <div><strong>DPI (Daerah Potensi Infestasi):</strong> Wilayah dengan potensi atau kejadian serangan OPT di periode tertentu.</div>
            </div>
        </div>
        <div>
            <h4 class="text-lg font-medium text-neutral-900 mb-2">Metode Pengumpulan</h4>
            <ol class="space-y-1 text-neutral-700">
                <li>1) Kompilasi laporan bulanan dari dinas pertanian daerah dan unit teknis pusat.</li>
                <li>2) Integrasi data iklim dari BMKG (curah hujan/suhu/kelembapan) sebagai variabel penjelas.</li>
                <li>3) Survei lapangan terpilih untuk verifikasi kejadian serangan OPT dan dampak.</li>
                <li>4) Rekonsiliasi lintas instansi dan validasi konsistensi antar-periode.</li>
            </ol>
        </div>
        <div>
            <h4 class="text-lg font-medium text-neutral-900 mb-2">Satuan & Periode</h4>
            <div class="space-y-2 text-neutral-700">
                <div><strong>Satuan:</strong> Sesuai variabel (mm untuk hujan, °C untuk suhu, % untuk kelembapan, ha atau kejadian untuk OPT/DPI).</div>
                <div><strong>Periode:</strong> Bulanan; konsolidasi tahunan dapat dilakukan untuk analisis tren.</div>
                <div><strong>Ketersediaan:</strong> Periode mengikuti pembaruan data bulanan pada basis data iklim/OPT/DPI.</div>
            </div>
        </div>
    </div>

    <div class="mt-8 p-4 bg-blue-50 border border-blue-200 rounded-lg">
        <h5 class="font-medium text-blue-900 mb-2">Catatan:</h5>
        <ul class="space-y-1 text-blue-800 text-sm">
            <li>• Tidak semua variabel tersedia pada setiap wilayah/bulan.</li>
            <li>• Perbedaan metodologi pencatatan daerah diperhatikan melalui pedoman harmonisasi.</li>
            <li>• Pembaruan data bersifat bertahap; angka dapat berubah seiring proses validasi.</li>
        </ul>
    </div>
</div>
