<div class="prose max-w-none">
    <h3 class="text-xl font-semibold text-neutral-900 mb-6">Metodologi Data Lahan</h3>

    <div class="grid md:grid-cols-2 gap-8">
        <div>
            <h4 class="text-lg font-medium text-neutral-900 mb-2">Sumber Data</h4>
            <ul class="space-y-1 text-neutral-700">
                <li>• Kementerian Pertanian Republik Indonesia</li>
                <li>• Direktorat Jenderal Prasarana dan Sarana Pertanian</li>
                <li>• Direktorat Jenderal Tanaman Pangan / Hortikultura / Perkebunan</li>
                <li>• Badan Pusat Statistik (BPS)</li>
                <li>• Dinas Pertanian Provinsi/Kabupaten</li>
            </ul>
        </div>
        <div>
            <h4 class="text-lg font-medium text-neutral-900 mb-2">Definisi Utama</h4>
            <div class="space-y-2 text-neutral-700">
                <div><strong>Luas Lahan:</strong> Luas area (hektar) yang digunakan untuk kegiatan pertanian tertentu.</div>
                <div><strong>Status Penggunaan:</strong> Kategori pemanfaatan lahan (sawah, tegalan, perkebunan, lahan tidur, dan lain-lain).</div>
                <div><strong>Konversi Lahan:</strong> Perubahan fungsi lahan dari pertanian ke non-pertanian atau sebaliknya.</div>
            </div>
        </div>
        <div>
            <h4 class="text-lg font-medium text-neutral-900 mb-2">Metode Pengumpulan</h4>
            <ol class="space-y-1 text-neutral-700">
                <li>1) Kompilasi administrasi dari pemerintah daerah dan kementerian teknis.</li>
                <li>2) Survei lapangan sampling untuk validasi angka luas dan status penggunaan.</li>
                <li>3) Integrasi citra satelit/akses peta tematik (jika tersedia) untuk cross-check.</li>
                <li>4) Rekonsiliasi dan verifikasi bersama instansi terkait.</li>
            </ol>
        </div>
        <div>
            <h4 class="text-lg font-medium text-neutral-900 mb-2">Satuan & Periode</h4>
            <div class="space-y-2 text-neutral-700">
                <div><strong>Satuan:</strong> Hektar (Ha), Persentase (%).</div>
                <div><strong>Periode:</strong> Tahunan; tidak ada pemilahan bulanan.</div>
                <div><strong>Ketersediaan:</strong> Tahun terakhir mengikuti update data pada basis data lahan.</div>
            </div>
        </div>
    </div>

    <div class="mt-8 p-4 bg-blue-50 border border-blue-200 rounded-lg">
        <h5 class="font-medium text-blue-900 mb-2">Catatan:</h5>
        <ul class="space-y-1 text-blue-800 text-sm">
            <li>• Angka dapat berubah seiring proses validasi dan perbaikan data.</li>
            <li>• Beberapa klasifikasi mungkin tidak tersedia untuk setiap tahun.</li>
            <li>• Perbedaan definisi antar sumber diselaraskan melalui pedoman statistik pertanian.</li>
        </ul>
    </div>
</div>
